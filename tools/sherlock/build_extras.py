"""Builds data/extras.js from tools/sherlock/extras/*.txt.

One file per episode, same name as its cards file (S01E01.txt...). First
line:  @ <section number>
Then one line per card (cards without extras can be left out):

    answer || ex1 | ex2 | ex3 | ex4 | ex5 || AmE equivalent | dated

- answer   exactly as in cards/<ep>.txt (the card id is derived from it the
           same way build.py does, so ids always match).
- ex       alternative practice sentences, ONE ___ each, same answer.
- AmE      American English equivalent; empty when it's the same / none.
- dated    the word "dated" for old-fashioned expressions; else empty.

Usage:  python tools/sherlock/build_extras.py
"""
import glob, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "data", "extras.js")

extras, problems = {}, []
for path in sorted(glob.glob(os.path.join(HERE, "extras", "*.txt"))):
    ep = os.path.basename(path)[:-4]
    lines = [l for l in open(path, encoding="utf-8").read().splitlines() if l.strip() and not l.startswith("#")]
    sec = int(lines[0][1:].strip())
    answers = set()
    cards_file = os.path.join(HERE, "cards", f"{ep}.txt")
    for l in open(cards_file, encoding="utf-8").read().splitlines()[1:]:
        if "||" in l:
            answers.add(l.split("||")[0].strip())
    for l in lines[1:]:
        parts = [p.strip() for p in l.split("||")]
        if len(parts) != 3:
            problems.append(f"{ep}: bad line {l[:60]}")
            continue
        ans, ex, tail = parts
        tail = (tail.split("|") + [""])[:2]
        us, dated = tail[0].strip(), tail[1].strip()
        if ans not in answers:
            problems.append(f"{ep}: '{ans}' is not a card in cards/{ep}.txt")
            continue
        cid = f"sh{sec:02d}_" + re.sub(r"[^a-z0-9]+", "-", ans.lower()).strip("-")
        entry = {}
        sentences = [s.strip() for s in ex.split(" | ") if s.strip()]
        for s in sentences:
            if s.count("___") != 1:
                problems.append(f"{ep}: '{ans}' example needs one ___: {s}")
        if sentences:
            entry["ex"] = sentences
        if us:
            entry["us"] = us
        if dated == "dated":
            entry["dated"] = True
        elif dated:
            problems.append(f"{ep}: '{ans}' last field must be 'dated' or empty")
        if entry:
            extras[cid] = entry

# Other books (vocab, blue, green): tools/extras/<book>/*.txt, keyed by the
# card id directly ("v01_001 || ex1 | ex2 ... || AmE | dated").
ROOT = os.path.join(HERE, "..", "..")
known_ids = set()
for f in ("vocab", "blue", "green"):
    known_ids |= set(re.findall(r'"?id"?:\s*"([^"]+)"', open(os.path.join(ROOT, "data", f + ".js"), encoding="utf-8").read()))
for path in sorted(glob.glob(os.path.join(ROOT, "tools", "extras", "*", "*.txt"))):
    name = os.path.relpath(path, os.path.join(ROOT, "tools", "extras"))
    for l in open(path, encoding="utf-8").read().splitlines():
        if not l.strip() or l.startswith("#"):
            continue
        parts = [p.strip() for p in l.split("||")]
        if len(parts) != 3:
            problems.append(f"{name}: bad line {l[:60]}")
            continue
        cid, ex, tail = parts
        if cid not in known_ids:
            problems.append(f"{name}: unknown card id {cid}")
            continue
        tail = (tail.split("|") + [""])[:2]
        us, dated = tail[0].strip(), tail[1].strip()
        entry = {}
        sentences = [s.strip() for s in ex.split(" | ") if s.strip()]
        for s in sentences:
            if s.count("___") != 1:
                problems.append(f"{name}: '{cid}' example needs one ___: {s}")
        if sentences:
            entry["ex"] = sentences
        if us:
            entry["us"] = us
        if dated == "dated":
            entry["dated"] = True
        elif dated:
            problems.append(f"{name}: '{cid}' last field must be 'dated' or empty")
        if entry:
            extras[cid] = entry

header = ("// Per-card extras, keyed by card id (see getExtras() in app.js):\n"
          "//   ex    — 5-6 alternative practice sentences, ONE ___ each, same answer\n"
          "//   us    — American English equivalent\n"
          "//   dated — old-fashioned expression (labelled, studied last, reviewed\n"
          "//           less often)\n"
          "// Generated by tools/sherlock/build_extras.py from tools/sherlock/extras/\n"
          "// and tools/extras/<book>/ (keyed by card id)\n"
          "// (no editar a mano). Kept apart from data/sherlock.js so that file can\n"
          "// keep being regenerated by build.py without losing any of this.\n")
# One card per line: readable diffs without the weight of full indentation.
body = ",\n".join(f"{json.dumps(k)}:{json.dumps(v, ensure_ascii=False, separators=(',', ':'))}" for k, v in extras.items())
open(OUT, "w", encoding="utf-8", newline="\n").write(
    header + "const CARD_EXTRAS = {\n" + body + "\n};\n")
print(len(extras), "cards with extras")
print("\n".join(problems) or "no problems")
